function setupPriceFilter(){

    const slider = document.getElementById("price-slider");
    const number = document.getElementById("max-price");

    slider.min = minPrice;
    slider.max = maxPrice;
    slider.value = selectedMaxPrice;

    number.min = minPrice;
    number.max = maxPrice;
    number.value = selectedMaxPrice;

    slider.oninput = function(){

        selectedMaxPrice = Number(this.value);

        number.value = selectedMaxPrice;

        updateProducts();

    };

    number.oninput = function(){

        let value = Number(this.value);

        if(value < minPrice){
            value = minPrice;
        }

        if(value > maxPrice){
            value = maxPrice;
        }

        selectedMaxPrice = value;

        slider.value = value;

        this.value = value;

        updateProducts();

    };

}

function selectCategory(category) {

    if (category === "") {

        selectedCategory = "";

        selectedMaxPrice = highestPrice;

        document.getElementById("price-slider").value = highestPrice;
        document.getElementById("max-price").value = highestPrice;

    }
    else if (selectedCategory === category) {

        selectedCategory = "";

    }
    else {

        selectedCategory = category;

    }

    document.querySelectorAll(".category-btn").forEach(button => {

        button.classList.remove("active");

        if (
            button.textContent.trim() === selectedCategory ||
            (selectedCategory === "" &&
             button.textContent.trim() === "No Filter")
        ) {
            button.classList.add("active");
        }

    });

    updateProducts();

}

function openYouTube(productId) {

    const videos = productVideos[productId];

    // No video yet
    if (!videos || videos.length === 0) {
        showYouTubeModal([]);
        return;
    }

    // Only one video → open it directly
    if (videos.length === 1) {
        window.open(videos[0], "_blank");
        return;
    }

    // Two or more videos → show parts popup
    showYouTubeModal(videos);
}


function showYouTubeModal(videos) {

    const modal = document.getElementById("youtube-modal");
    const videoList = document.getElementById("youtube-video-list");

    videoList.innerHTML = "";

    // No video available
    if (videos.length === 0) {

        const message = document.createElement("p");

        message.textContent = "YouTube video coming soon!";

        message.className = "youtube-coming-soon";

        videoList.appendChild(message);

    } else {

        videos.forEach((video, index) => {

            const button = document.createElement("button");

            button.className = "youtube-part-btn";

            button.innerHTML = `▶ Part ${index + 1}`;

            button.onclick = function () {

                window.open(video, "_blank");

                closeYouTubeModal();

            };

            videoList.appendChild(button);

        });

    }

    modal.style.display = "flex";
}


